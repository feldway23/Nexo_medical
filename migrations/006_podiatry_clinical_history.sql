-- Nexo Medical: structured podiatry clinical history record.
CREATE TABLE IF NOT EXISTS podiatry_clinical_histories (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 patient_id UUID NOT NULL REFERENCES patients(id),
 encounter_id UUID REFERENCES clinical_encounters(id),
 professional_id UUID REFERENCES professionals(id),
 attended_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 encounter_type TEXT NOT NULL DEFAULT 'initial',
 reason_for_consultation TEXT NOT NULL,
 current_illness TEXT,
 personal_history JSONB NOT NULL DEFAULT '{}'::jsonb,
 family_history TEXT,
 medication_history TEXT,
 allergy_history TEXT,
 systems_review JSONB NOT NULL DEFAULT '{}'::jsonb,
 pain_scale SMALLINT CHECK (pain_scale BETWEEN 0 AND 10),
 laterality TEXT CHECK (laterality IN ('right','left','bilateral','not_applicable')),
 skin_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 nail_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 interdigital_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 vascular_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 neurological_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 biomechanical_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 footwear_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 wounds_exam JSONB NOT NULL DEFAULT '{}'::jsonb,
 functional_exam TEXT,
 clinical_analysis TEXT,
 diagnoses JSONB NOT NULL DEFAULT '[]'::jsonb,
 procedures JSONB NOT NULL DEFAULT '[]'::jsonb,
 treatment_plan TEXT,
 recommendations TEXT,
 referrals TEXT,
 follow_up TEXT,
 consent_record JSONB NOT NULL DEFAULT '{}'::jsonb,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','signed','amended')),
 signed_by TEXT,
 professional_registration TEXT,
 signed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS podiatry_history_patient_date_idx ON podiatry_clinical_histories(patient_id, attended_at DESC);
CREATE INDEX IF NOT EXISTS podiatry_history_professional_idx ON podiatry_clinical_histories(professional_id, attended_at DESC);